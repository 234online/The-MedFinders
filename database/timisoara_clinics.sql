-- =====================================================================
--  TIMIȘOARA CLINICS DATABASE  (PostgreSQL)
--  100 clinics, hospitals, laboratories and practices in Timișoara.
--  Data researched on 2026-11-13 from official clinic / hospital websites,
--  network location pages (MedLife, Regina Maria, Bioclinica, Synevo,
--  Clinica Sante), the ROmedic directory and OpenStreetMap.
--  Map coordinates: ROmedic / Synevo / OpenStreetMap pins, or geocoded
--  from the address with OpenStreetMap Nominatim.
--
--  INCLUSION RULE: a place is listed ONLY if a source gave ALL of:
--  name, street address, phone number, opening hours and at least one
--  specialty. Places with anything missing were left out on purpose.
--  Every clinic has at least one source URL in the clinic_sources table.
--
--  NO EMPTY VALUES in the clinics table: when a clinic publishes no email
--  or website the text 'not listed' is stored, an unconfirmed CNAS
--  contract is 'unknown', and a clinic outside any chain is 'Independent'.
--
--  HOW TO RUN:
--  pgAdmin -> right-click Clinics_db -> Query Tool -> Open File (folder icon)
--  -> choose this file -> press F5.  You can run it again any time:
--  it deletes the old tables first and rebuilds everything.
-- =====================================================================

BEGIN;   -- start a transaction: either everything succeeds, or nothing changes

-- ---------------------------------------------------------------------
-- 0. Clean start (drop in reverse order of dependencies)
-- ---------------------------------------------------------------------
DROP VIEW  IF EXISTS v_clinic_overview;
DROP TABLE IF EXISTS ratings, clinic_sources, doctor_schedules,
                     doctor_assignments, doctors, opening_hours,
                     clinic_specialties, specialties, clinics CASCADE;

-- ---------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------

-- One row per clinic / hospital / medical centre
CREATE TABLE clinics (
    clinic_id     INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code          VARCHAR(40)  NOT NULL UNIQUE,   -- short readable key, used to link data
    name          VARCHAR(200) NOT NULL,
    network       VARCHAR(80)  NOT NULL,          -- e.g. MedLife, Regina Maria, or 'Independent'
    ownership     VARCHAR(10)  NOT NULL
                  CHECK (ownership IN ('public', 'private', 'ngo')),
    kind          VARCHAR(20)  NOT NULL
                  CHECK (kind IN ('hospital', 'polyclinic', 'clinic', 'dental',
                                  'laboratory', 'imaging', 'practice', 'university clinic')),
                  -- practice = a single doctor's / psychologist's own office (cabinet individual)
    address       VARCHAR(250) NOT NULL,          -- required: no address = not listed
    postal_code   VARCHAR(10)  NOT NULL,          -- 'not listed' when it could not be confirmed
    phone         VARCHAR(60)  NOT NULL,          -- required: no phone = not listed
    email         VARCHAR(100) NOT NULL,          -- 'not listed' when the clinic publishes none
    website       VARCHAR(150) NOT NULL,          -- 'not listed' when the clinic has none
    cnas_contract VARCHAR(10)  NOT NULL           -- works with the state health insurance?
                  CHECK (cnas_contract IN ('yes', 'no', 'unknown')),
    latitude      NUMERIC(9,6) NOT NULL,          -- map position (WGS84, same system as Google Maps / Leaflet)
    longitude     NUMERIC(9,6) NOT NULL,
    geo_precision VARCHAR(10)  NOT NULL DEFAULT 'exact'
                  CHECK (geo_precision IN ('exact', 'street')),
                  -- exact = pin is on the building; street = pin is only on the right street
    notes         TEXT         NOT NULL,
    specialties   TEXT                            -- readable list, filled automatically in step 4
);

-- List of medical specialties
CREATE TABLE specialties (
    specialty_id  INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL UNIQUE,
    name_ro       VARCHAR(80)  NOT NULL,
    name_en       VARCHAR(80)  NOT NULL,
    category_ro   VARCHAR(40)  NOT NULL,          -- group shown in the filter menu
    category_en   VARCHAR(40)  NOT NULL
);

-- Which clinic offers which specialty  (MANY-TO-MANY link table)
CREATE TABLE clinic_specialties (
    clinic_id     INTEGER REFERENCES clinics(clinic_id)       ON DELETE CASCADE,
    specialty_id  INTEGER REFERENCES specialties(specialty_id) ON DELETE CASCADE,
    PRIMARY KEY (clinic_id, specialty_id)          -- the same pair cannot appear twice
);

-- Opening hours: one row per clinic per day
-- (a day with no row = the source did not state hours for that day)
CREATE TABLE opening_hours (
    clinic_id     INTEGER  NOT NULL REFERENCES clinics(clinic_id) ON DELETE CASCADE,
    day_of_week   SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- 1 = Monday ... 7 = Sunday
    open_time     TIME,
    close_time    TIME,                            -- close < open means "runs past midnight"
    is_closed     BOOLEAN  NOT NULL DEFAULT FALSE,
    is_24h        BOOLEAN  NOT NULL DEFAULT FALSE,
    notes         VARCHAR(150),                    -- e.g. a midday break
    PRIMARY KEY (clinic_id, day_of_week)
);

-- Doctors (people), independent of where they work
CREATE TABLE doctors (
    doctor_id     INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL UNIQUE,
    title         VARCHAR(120),        -- Medic Primar, Medic Specialist, Prof. Univ. Dr., Psiholog ...
    notes         TEXT
);

-- Doctor X works at clinic Y in specialty Z  (a doctor can work in several clinics)
CREATE TABLE doctor_assignments (
    assignment_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    doctor_id     INTEGER NOT NULL REFERENCES doctors(doctor_id)        ON DELETE CASCADE,
    clinic_id     INTEGER NOT NULL REFERENCES clinics(clinic_id)        ON DELETE CASCADE,
    specialty_id  INTEGER          REFERENCES specialties(specialty_id),
    role          VARCHAR(120),        -- e.g. 'Head of clinic', 'Manager'
    UNIQUE (doctor_id, clinic_id, specialty_id)
);

-- When a doctor consults at a given clinic
CREATE TABLE doctor_schedules (
    assignment_id INTEGER  NOT NULL REFERENCES doctor_assignments(assignment_id) ON DELETE CASCADE,
    day_of_week   SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time    TIME     NOT NULL,
    end_time      TIME     NOT NULL CHECK (end_time > start_time),
    PRIMARY KEY (assignment_id, day_of_week, start_time)
);

-- Public ratings (aggregate scores only, with where they came from)
CREATE TABLE ratings (
    rating_id     INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    clinic_id     INTEGER      NOT NULL REFERENCES clinics(clinic_id) ON DELETE CASCADE,
    platform      VARCHAR(50)  NOT NULL,       -- romedic.ro, sfatulmedicului.ro ...
    score         NUMERIC(3,1) NOT NULL,
    max_score     NUMERIC(3,1) NOT NULL DEFAULT 5,
    votes         INTEGER,
    retrieved_on  DATE         NOT NULL,
    source_url    VARCHAR(300) NOT NULL,
    CHECK (score >= 0 AND score <= max_score)
);

-- Where each piece of information came from
CREATE TABLE clinic_sources (
    clinic_id     INTEGER      NOT NULL REFERENCES clinics(clinic_id) ON DELETE CASCADE,
    url           VARCHAR(300) NOT NULL,
    confirms      VARCHAR(200),               -- what this source confirms
    retrieved_on  DATE         NOT NULL DEFAULT DATE '2026-11-13',
    PRIMARY KEY (clinic_id, url)
);

