-- 10. A VIEW: a saved query that gives a readable summary of each clinic
-- ---------------------------------------------------------------------
CREATE VIEW v_clinic_overview AS
SELECT
    c.name,
    c.network,
    c.ownership,
    c.kind,
    c.address,
    c.phone,
    c.specialties,
    COUNT(DISTINCT da.doctor_id)                    AS doctors_listed,
    MAX(r.score)                                    AS best_rating
FROM clinics c
LEFT JOIN clinic_specialties cs ON cs.clinic_id = c.clinic_id
LEFT JOIN specialties        s  ON s.specialty_id = cs.specialty_id
LEFT JOIN doctor_assignments da ON da.clinic_id = c.clinic_id
LEFT JOIN ratings            r  ON r.clinic_id = c.clinic_id
GROUP BY c.clinic_id
ORDER BY c.name;

